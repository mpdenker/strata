/** The icon key for a name: an icon key itself, or an SF Symbol name. null if nothing matches. */
export function resolveIcon(name) {
  if (!name) return null;
  if (P[name]) return name;
  for (const [re, key] of RULES) if (re.test(name)) return key;
  return null;
}

/** Inline SVG markup for an icon. Decorative (hidden from screen readers) unless a label is given. */
export function icon(name, { cls = '', label } = {}) {
  const key = resolveIcon(name) ?? 'dot';
  const a11y = label ? `role="img" aria-label="${label.replace(/"/g, '&quot;')}"` : 'aria-hidden="true"';
  return `<svg class="ic ${cls}" viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="1.8" stroke-linecap="round" stroke-linejoin="round" ${a11y}>${P[key]}</svg>`;
}
